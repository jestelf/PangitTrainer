def system_language():
    try:
        lcid = ctypes.windll.kernel32.GetUserDefaultUILanguage() & 0x3ff
    except (AttributeError, OSError):
        return 'en'
    return 'ru' if lcid in (0x19, 0x22, 0x23, 0x3f) else 'en'

def set_language(code):
    global _language
    _language = 'en' if code == 'en' else 'ru'

def current():
    return _language

def T(text):
    return EN.get(text, text) if _language == 'en' else text
